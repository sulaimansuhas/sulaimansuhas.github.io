const fs = require('node:fs');
const path = require('node:path');
const matter = require('gray-matter');

// GitHub Actions checks out sulaimansuhas/Moria here before importing.
// Never read the user's local Obsidian vault.
const vault = path.join(__dirname, '../.shelf-vault');
if (!fs.existsSync(vault)) {
  throw new Error('Missing GitHub vault checkout. This importer runs after Fetch shelf collections in GitHub Actions.');
}
const collections = [
  ['book', 'ReadingList/Books', 'author', 'cover'],
  ['film', 'WatchingList/Movies', 'director', 'poster'],
];
const text = value => value == null ? '' : String(value).trim();
const entries = collections.flatMap(([kind, folder, creator, image]) => {
  const directory = path.join(vault, folder);
  return fs.readdirSync(directory).sort().filter(name => name.endsWith('.md') && !/template/i.test(name)).flatMap(name => {
    const { data, content } = matter(fs.readFileSync(path.join(directory, name), 'utf8'));
    if (data.publish === false) return [];
    const imageUrl = text(data[image]);
    if (imageUrl && !/^https?:\/\//i.test(imageUrl)) throw new Error(`${name}: cover/poster must be an HTTP(S) URL`);
    return [{
      kind, title: text(data.title) || name.slice(0, -3),
      creator: text(data[creator]), image: imageUrl,
      status: text(data.status), rating: text(data.rating), year: text(data.year),
      notes: content.replace(/^\s*#\s+Notes\s*$/gm, '').trim(),
    }];
  });
});
const output = path.join(__dirname, '../src/data/shelf.ts');
fs.writeFileSync(output, '// Generated by npm run import-shelf.\nexport default ' + JSON.stringify(entries, null, 2) + '\n');
console.log(`Imported ${entries.filter(e => e.kind === 'book').length} books and ${entries.filter(e => e.kind === 'film').length} films.`);
